// For any run not explicitly mocked, generate a simple trace
export function getRunDetail(runId: string): RunDetail | null {
  if (mockRunDetails[runId]) return mockRunDetails[runId]
  const run = mockRuns.find(r => r.id === runId)
  if (!run) return null
  return {
    run,
    events: [
      {
        id: `${runId}-evt-1`,
        step_id: `${runId}-step-1`,
        parent_step_id: null,
        step_type: 'llm_call',
        step_name: 'process_input',
        input: { data: 'sample input' },
        output: { result: 'sample output' },
        status: run.status === 'running' ? 'success' : run.status,
        error_message: run.status === 'success' || run.status === 'running' ? null : run.error_message,
        timestamp: run.started_at,
        duration_ms: run.duration_ms ? Math.floor(run.duration_ms * 0.4) : null,
        metadata: {},
        children: [],
      },
      {
        id: `${runId}-evt-2`,
        step_id: `${runId}-step-2`,
        parent_step_id: null,
        step_type: 'tool_call',
        step_name: 'execute_action',
        input: { action: 'process' },
        output: { completed: true },
        status: run.status === 'running' ? 'success' : run.status,
        error_message: null,
        timestamp: new Date(new Date(run.started_at).getTime() + (run.duration_ms ? run.duration_ms * 0.4 : 1000)).toISOString(),
        duration_ms: run.duration_ms ? Math.floor(run.duration_ms * 0.6) : null,
        metadata: {},
        children: [],
      },
    ],
  }
}

